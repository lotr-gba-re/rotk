"""Stores -> armips equates + ld PROVIDEs.

Emits two generated artifacts so hacks reference game functions/globals by name instead of
hardcoded addresses:

  build/game_symbols.inc  (armips, for asm hacks):
    config/functions.cfg  -> <name> equ <addr>        (even address; mode in comment)
    data stores           -> <name> equ <addr>

  build/game_symbols.ld   (ld, for C hacks - INCLUDE it from a hack linker script):
    config/functions.cfg  -> PROVIDE(<name> = <addr> | 1);   (thumb rows: thumb bit set)
                             PROVIDE(<name> = <addr>);       (arm rows)
    data stores           -> PROVIDE(<name> = <addr>);

Thumb convention: armips equates are the even address (the |1 thumb bit is applied at the
call site or by `thumbVeneer`); the linker PROVIDEs of thumb functions carry the |1 so
gcc's interworking `bx` stays in thumb, while ARM functions PROVIDE the plain address.
"""

import os

from rotkit.paths import BUILD, ROOT

from rotkit.stores import FUNCS_CFG as FUNCS, data_rows, rows as read_rows

OUT = BUILD / "game_symbols.inc"
OUT_LD = BUILD / "game_symbols.ld"

MACRO = """\
; thumb veneer: load Func|1 and branch (the long-range trampoline tail)
.macro thumbVeneer, reg, target
    ldr reg,=(target|1)
    bx  reg
.endmacro
"""


def equ(name: str, value: str | int, comment: str = "") -> str:
    note = f"   ; {comment}" if comment else ""
    return f"{name:<40} equ {value}{note}\n"


def run() -> None:
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    n_funcs = n_data = 0
    with open(OUT, "w") as fh:
        fh.write(
            "; GENERATED by rotkit build symbols - do not edit. (.include this in a hack)\n"
        )
        fh.write(
            "; Function equates are EVEN addresses; apply |1 for thumb calls (see thumbVeneer).\n\n"
        )

        fh.write("; ===== functions =====\n")
        for addr, mode, name in read_rows(FUNCS, 3):
            fh.write(equ(name, addr, mode))
            n_funcs += 1

        fh.write("\n; ===== data globals =====\n")
        for addr, name, sym_type in data_rows():
            fh.write(equ(name, addr, sym_type))
            n_data += 1

        fh.write(MACRO)

    n_funcs_ld = n_data_ld = 0
    with open(OUT_LD, "w") as fh:
        fh.write("/* GENERATED by rotkit build symbols - do not edit. */\n")
        fh.write(
            "/* INCLUDE from a hack linker script. THUMB funcs carry |1; ARM funcs and data are plain. */\n\n"
        )
        for addr, mode, name in read_rows(FUNCS, 3):
            thumb_bit = " | 1" if mode == "thumb" else ""
            fh.write(f"PROVIDE({name} = {addr}{thumb_bit});\n")
            n_funcs_ld += 1
        fh.write("\n")
        for addr, name, _sym_type in data_rows():
            fh.write(f"PROVIDE({name} = {addr});\n")
            n_data_ld += 1

    print(f"wrote {os.path.relpath(OUT, ROOT)}: {n_funcs} functions, {n_data} data")
    print(
        f"wrote {os.path.relpath(OUT_LD, ROOT)}: {n_funcs_ld} functions, {n_data_ld} data"
    )
