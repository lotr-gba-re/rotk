"""Data stores (config/data.cfg + carved/config/*.cfg) -> build/include/variables.h, one
`extern <type> <name>;` per typed data symbol so matched C references game globals by name.
Addresses are bound at link time by rotkit build cc. ROM data (addr >= ROMBASE) is declared
`const`, matching the definitions the carvers emit; untyped symbols are skipped.
"""

import os

from rotkit.paths import BUILD_INCLUDE, CARVED_INCLUDE, INCLUDE, ROOT
from rotkit.rom import ROMBASE

from rotkit.stores import data_rows

OUT = BUILD_INCLUDE / "variables.h"


def _join(type_base: str, name: str) -> str:
    """Space-separate a plain type from the name, but glue a pointer base to it the way
    clang-format's (Microsoft) PointerAlignment does: `u8 Name`, `u8 *Name` (no space)."""
    base = type_base.strip()
    sep = "" if base.endswith("*") else " "
    return f"{base}{sep}{name}"


def decl(addr: int, name: str, type_str: str) -> str | None:
    type_str = type_str.strip()
    if not type_str:
        return None  # untyped - can't declare
    const = "const " if addr >= ROMBASE else ""
    bracket = type_str.find("[")
    if bracket >= 0:  # array: `Foo[5]` -> `Foo name[5];`
        return f"extern {const}{_join(type_str[:bracket], name)}{type_str[bracket:]};"
    return f"extern {const}{_join(type_str, name)};"


def run() -> None:
    decls, skipped = [], []
    for addr, name, type_str in data_rows():
        declaration = decl(int(addr, 16), name, type_str)
        if declaration:
            decls.append(declaration)
        else:
            skipped.append(name)

    os.makedirs(OUT.parent, exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write(
            "/* GENERATED by rotkit build variables - extern decls for game globals,\n"
        )
        fh.write(
            " * from the data stores. Addresses are bound by rotkit build cc at link time. */\n"
        )
        fh.write("#pragma once\n")
        # types.h + module headers: a global may be typed with a struct from a subsystem
        # header (e.g. EnemyTypeInfo in enemy.h, ShopCursorPos in scene/shop.h), from any
        # subdirectory. Sorted for clang-format SortIncludes order, so the generated file
        # is format-clean as written.
        headers = [
            p.relative_to(root).as_posix()
            for root in (INCLUDE, CARVED_INCLUDE)
            for p in root.rglob("*.h")
        ]
        for header in sorted(headers):
            fh.write(f'#include "{header}"\n')
        fh.write("\n")
        fh.write("\n".join(decls) + "\n")

    print(
        f"wrote {os.path.relpath(OUT, ROOT)}: {len(decls)} globals"
        + (
            f" ({len(skipped)} untyped skipped: {', '.join(skipped)})"
            if skipped
            else ""
        )
    )
