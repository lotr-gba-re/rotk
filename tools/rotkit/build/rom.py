"""Emit build/rom.s: the whole ROM as an ordered list of `.incbin`s.

The decompiled pieces are already compiled to final bytes (build/split/<...>.bin by the
Makefile's standard per-file rules); everything else is still the base ROM. So the full image
is just a concatenation, in address order, of those .bin files and base-ROM gaps:

    .incbin "rotk.gba", <gap file-offset>, <gap len>     @ un-decompiled remainder
    .incbin "build/split/c/combat_rollAccuracy.bin"          @ a decompiled region
    ...

`make verify` then assembles this (as -> objcopy -> build/rom.gba) and checks
sha1(build/rom.gba) == base. Reads config/split.cfg.
"""

import os
import sys

from rotkit.paths import BUILD, ROOT
from rotkit.rom import ROM, ROMBASE, regions

OUT = BUILD / "rom.s"


def run() -> None:
    if not os.path.isfile(ROM):
        sys.exit("build rom: rotk.gba missing (gitignored) - cannot fill gaps.")
    romsize = os.path.getsize(ROM)
    lines = [
        "@ GENERATED by rotkit build rom - the whole ROM as ordered .incbin.",
        "@ Gaps come from the local base ROM; decompiled regions from build/split/*.bin.",
        '.section .rom, "a"',
    ]
    cursor = 0
    rows = regions()
    for r in rows:
        offset = r.addr - ROMBASE  # split.cfg address as ROM file offset
        if offset < cursor:
            sys.exit(
                f"build rom: region {r.src} @ file 0x{offset:x} overlaps the previous region"
            )
        if not os.path.isfile(r.bin_path):
            sys.exit(
                f"build rom: {os.path.relpath(r.bin_path, ROOT)} missing - build it (make verify)"
            )
        if offset > cursor:
            lines.append(f'    .incbin "rotk.gba", 0x{cursor:x}, 0x{offset - cursor:x}')
        lines.append(
            f'    .incbin "{os.path.relpath(r.bin_path, ROOT)}"   @ {os.path.relpath(r.src, ROOT)}'
        )
        cursor = offset + os.path.getsize(r.bin_path)
    if cursor < romsize:
        lines.append(f'    .incbin "rotk.gba", 0x{cursor:x}, 0x{romsize - cursor:x}')

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(lines) + "\n")
    src_bytes = sum(os.path.getsize(r.bin_path) for r in rows)
    print(
        f"build rom: wrote {os.path.relpath(OUT, ROOT)} - {len(rows)} regions from source "
        f"({src_bytes} B, {100.0 * src_bytes / romsize:.3f}%), rest .incbin from base ROM"
    )
