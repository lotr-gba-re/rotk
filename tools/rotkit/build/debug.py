"""Stores + headers + decompiled C -> a gdb symbol/type bundle for mGBA's GDB stub.

Emits build/debug/:

  debug.elf      every store symbol at its address (functions section-relative, ARM/Thumb per
                 functions.cfg, so break/disassemble pick the right mode); DWARF: every
                 include/*.h struct and every typed config/data.cfg global (as extern decls -
                 gdb resolves their addresses from the symtab, so `p g_PlayerGlobals.players[0]` just works)
  debug_stubs.elf  DWARF subprograms for store functions that have a header prototype but no
                 decompiled source: stub definitions (empty bodies, placed at the real
                 addresses) so `break <func>` shows typed arguments with their incoming
                 register values. Not real code - no line info (stripped), entry range only.
  tu/<stem>.elf  per split.cfg src/c TU, built by rotkit.compile with -g (DWARF from agbcc): args,
                 locals and line info for decompiled functions; .text holds the matched bytes
  utils.gdb      small gdb utilities for the session (`settle`: run the game to the main-loop
                 tick so inferior calls start from a sane user-mode context); sourced by
                 rotk.gdb / rotk_hack.gdb
  rotk.gdb       loads all of the above, connects to the stub:

                     mgba-qt -g rotk.gba             # stub on :2345, break at entry
                     gdb -x build/debug/rotk.gdb     # arm-none-eabi-gdb or any ARM-capable gdb

  rotk_hack.gdb  same, plus the modcode (symbols + line info) from build/hack.elf;
                 debug `make hack`'s build/rotk_hack.gba with it
"""

import functools
import os
import re
import shutil
from pathlib import Path

from rotkit.build import variables
from rotkit.compile import compile_file, run_tool
from rotkit.decomp import prototypes_in_header
from rotkit.paths import BUILD, BUILD_INCLUDE, CARVED_INCLUDE, INCLUDE, ROOT
from rotkit.rom import ROMBASE
from rotkit.stores import data_rows
from rotkit.stores import func_symbols, read_split

OUT = BUILD / "debug"

GDB_SETTINGS = """\
set confirm off
set pagination off
set print pretty on
set mem inaccessible-by-default off
set arm force-mode auto

# mGBA's stub does not halt on attach (DEBUGGER_ENTER_ATTACHED sends no stop);
# interrupt on connect so the game is deterministically paused when gdb attaches
# and the remaining -x scripts (e.g. audio.gdb) load without a manual Ctrl-C.
set remote interrupt-on-connect on

# Force hex ($M) memory writes: gdb binary-writes values containing NUL bytes as $X
# packets, and the mGBA master gdb stub's packet parser (commit 7944bb4) treats a NUL
# payload byte as end-of-message and NAKs them, hanging gdb on
# "Ignoring packet error, continuing...". Hex $M avoids it; harmless on 0.10.5 and
# removable once upstream fixes the parser.
set remote X-packet off
"""

GDB_SCRIPT = """\
# GENERATED by rotkit build debug - do not edit.
# mGBA GDB stub: symbols (stores) + DWARF types (include/*.h) for the running game.
#
#   mgba-qt -g rotk.gba            # stub on :2345 (-g also breaks at entry)
#   gdb -x {script}                # arm-none-eabi-gdb or any ARM-capable gdb
#
# Then: p g_PlayerGlobals.players[0]   ptype SaveSlot   break combat_resolvePveAttack   info args
#       settle   (run the game to the main-loop tick; see {utils})

{settings}
file {elf}
{adds}
source {utils}
target remote localhost:2345
"""

GDB_HACK_SCRIPT = """\
# GENERATED by rotkit build debug - do not edit.
# mGBA GDB stub for the hack build: rotk.gdb plus the modcode (symbols + line info) from
# build/hack.elf (needs `make hack` first).
#
#   mgba-qt -g build/rotk_hack.gba
#   gdb -x {script}
#
# Then: break menu_text_run   list   p g_PlayerGlobals.players[0]   (game symbols/types all work too)
#       settle   (run the game to the main-loop tick; see {utils})

{settings}
file {elf}
{adds}
add-symbol-file {modcode}
source {utils}
target remote localhost:2345
"""

UTILS_GDB = """\
# GENERATED by rotkit build debug - do not edit.
# Small gdb utilities for the mGBA stub session (sourced by rotk.gdb / rotk_hack.gdb).
# Plain gdb (no embedded python).
#
#   settle    run the game to the main-loop tick (user-mode main loop) and stop there.
#             A Ctrl-C can stop the game inside the IWRAM IRQ handler (mixer timer); an
#             inferior call started from there runs in IRQ mode and corrupts the call
#             frame. Settle first, then call/poke game state safely.
#             Notes: disable/enable is all-or-nothing (a breakpoint you had disabled
#             before settle gets re-enabled); keep the `commands` block to just `silent`
#             (a `disable` inside is restored by gdb's commands bookkeeping and would
#             clobber the `enable`).

# rotk_main's per-iteration update call (0x080315f6 = rotk_main+0xae): the canonical
# sane user-mode stop. Raw even address: the thumb-bit symbol value would be off by one.
define settle
    if $pc < 0x02000000
        printf "settle: stop PC 0x%08x is outside real memory (corrupt session?); restart mGBA + gdb if the run below fails\\n", $pc
    end
    disable
    break *0x080315f6
    commands
        silent
    end
    continue
    enable
    clear *0x080315f6
    printf "settle: stopped at the main-loop tick\\n"
end
"""

LINK_LD = (
    """\
/* GENERATED by rotkit build debug - do not edit. */
SECTIONS {
  . = %#x;
  .rotk_text . : { *(.rotk_text) }
}
"""
    % ROMBASE
)


_run = functools.partial(run_tool, prefix="debug")


def _gen_syms_s(path) -> tuple[int, int]:
    """stores -> one .S of function labels + data absolutes.

    Functions must be section-relative (not .set absolutes): gdb classifies ABS syms as
    mst_abs and refuses `break <name>` on them. .org places each label at its ROM offset;
    .thumb_func sets st_value bit 0, which bfd maps to ST_BRANCH_TO_THUMB, so breakpoints
    and disassembly use thumb mode. GAS auto-stamps a $d mapping symbol over the zero fill
    (overrides the thumb bit in arm_pc_is_thumb) - stripped post-link.
    """
    n_funcs = n_data = 0
    with open(path, "w") as fh:
        fh.write("/* GENERATED by rotkit build debug - do not edit. */\n")
        fh.write("    .syntax unified\n")
        fh.write('    .section .rotk_text, "ax", %progbits\n')
        for sym in func_symbols():
            fh.write(f"    .org {sym.addr - ROMBASE:#x}\n")
            fh.write(f"    .global {sym.name}\n    .type {sym.name}, %function\n")
            if sym.mode == "thumb":
                fh.write("    .thumb_func\n")
            fh.write(f"{sym.name}:\n")
            n_funcs += 1
        for addr, name, _type in data_rows():
            fh.write(f"    .global {name}\n    .type {name}, %object\n")
            fh.write(f"    .set {name}, {addr}\n")
            n_data += 1
    return n_funcs, n_data


# --- stage A: decompiled TUs with agbcc DWARF -----------------------------------------------


def _build_tu_elfs() -> list[tuple[Path, list[str]]]:
    """split.cfg src/c TUs -> (kept ELF, defined store functions) with -g DWARF."""
    out = []
    for src in sorted(read_split()):
        if not src.startswith("src/c/"):
            continue
        elf = OUT / "tu" / f"{Path(src).stem}.elf"
        compile_file(src, keep_elf=str(elf), debug=True)
        nm = _run("arm-none-eabi-nm", str(elf)).stdout
        defined = [
            cols[2]
            for line in nm.splitlines()
            if len(cols := line.split()) == 3 and cols[1] in ("T", "t")
        ]
        out.append((elf, defined))
    return out


# --- stage B: prototype stubs for the prototyped rest ----------------------------------------


def _header_prototypes() -> dict[str, str]:
    """include/*.h -> {store func name: prototype text} (via the shared header parser)."""
    wanted = {s.name for s in func_symbols()}
    protos: dict[str, str] = {}
    for header in sorted(INCLUDE.rglob("*.h")):
        for name, proto in prototypes_in_header(header).items():
            if name in wanted:
                protos[name] = proto
    return protos


def _split_params(proto: str) -> list[str]:
    """Prototype -> parameter declarations (top-level comma split)."""
    args = proto[proto.index("(") + 1 : proto.rindex(")")].strip()
    if args in ("", "void"):
        return []
    parts, depth, cur = [], 0, ""
    for ch in args:
        depth += (ch == "(") - (ch == ")")
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    parts.append(cur)
    return parts


def _param_name(decl: str) -> str:
    """Parameter declaration -> its name (last identifier; fn-pointer aware)."""
    m = re.search(r"\(\s*\*\s*([A-Za-z_]\w*)", decl)  # fn-pointer: void (*cb)(int)
    return m.group(1) if m else re.findall(r"[A-Za-z_]\w*", decl)[-1]


def _composite_typedefs() -> set[str]:
    """Struct/union typedef names (the fused `typedef struct X { ... } X;` definitions)."""
    names = set()
    for path in INCLUDE.rglob("*.h"):
        text = path.read_text(encoding="utf-8")
        names.update(re.findall(r"typedef\s+(?:struct|union)\s+(\w+)", text))
    return names


def _stub_body(proto: str, composite: set[str]) -> tuple[list[str], list[str]]:
    """Prototype -> (register-local declarations, asm pin operands).

    Scalars pin directly to their incoming ABI register. A by-value struct/union can't:
    GCC homes BLKmode params to a frame slot, but the stub body is never executed (the
    ELF only donates symbols/DWARF at the ROM address), so that location would read stack
    garbage. Instead its incoming word is exposed as a register local <name>_word pinned
    to the right argument register (valid while params are one word each and <= 4 total).
    """
    lines, pins = [], []
    for i, decl in enumerate(_split_params(proto)):
        name = _param_name(decl)
        base = decl[: decl.rfind(name)].strip()
        if "*" not in base and base.split()[-1] in composite:
            lines.append(f'    register u32 {name}_word asm("r{i}");')
            pins.append(f'"r"({name}_word)')
        else:
            pins.append(f'"r"({name})')
    return lines, pins


def _build_stubs_elf(
    protos: dict[str, str], defined: set[str]
) -> tuple[Path | None, int]:
    """Stub definitions for prototyped, not-decompiled store functions -> placed ELF.

    Empty bodies whose params are pinned to their incoming ABI registers via an asm input,
    so DWARF locations read the real argument values at function entry. Compiled
    -ffunction-sections and each section linked at the store address; .debug_line stripped
    (the generated file is not real source). ARM/Thumb per functions.cfg.
    """
    stubs = [s for s in func_symbols() if s.name in protos and s.name not in defined]
    if not stubs:
        return None, 0
    composite = _composite_typedefs()
    objects = []
    for mode, march in (("thumb", "-mthumb"), ("arm", "-marm -mthumb-interwork")):
        names = [s.name for s in stubs if s.mode == mode]
        if not names:
            continue
        stub_c = OUT / f"stubs_{mode}.c"
        with open(stub_c, "w") as fh:
            fh.write("/* GENERATED by rotkit build debug - do not edit. */\n")
            fh.write('#include "variables.h"\n')
            for name in names:
                lines, pins = _stub_body(protos[name], composite)
                fh.write(f"{protos[name]}\n{{\n")
                for line in lines:
                    fh.write(line + "\n")
                fh.write(f'    __asm__ volatile("" : : {", ".join(pins)});\n}}\n')
        obj = OUT / f"stubs_{mode}.o"
        _run(
            "arm-none-eabi-gcc",
            "-c",
            "-g3",
            "-O2",
            "-std=gnu11",
            "-ffreestanding",
            *march.split(),
            "-mcpu=arm7tdmi",
            "-ffunction-sections",
            "-w",
            f"-I{INCLUDE}",
            f"-I{CARVED_INCLUDE}",
            f"-I{BUILD_INCLUDE}",
            str(stub_c),
            "-o",
            str(obj),
        )
        objects.append(obj)

    sections = "\n".join(
        f"  .text.{s.name} 0x{s.addr:08x} : {{ *(.text.{s.name}) }}" for s in stubs
    )
    link_ld = OUT / "stubs.ld"
    link_ld.write_text(
        f"/* GENERATED by rotkit build debug - do not edit. */\n"
        f"SECTIONS {{\n  . = {ROMBASE:#x};\n{sections}\n}}\n"
    )
    elf = OUT / "debug_stubs.elf"
    _run(
        "arm-none-eabi-ld",
        "--entry=0",
        "-T",
        str(link_ld),
        "-o",
        str(elf),
        *(str(o) for o in objects),
    )
    # the stub "source" is generated noise; keep .debug_info (args/types), drop line info
    _run("arm-none-eabi-objcopy", "--remove-section", ".debug_line", str(elf))
    return elf, len(stubs)


# --- bundle ----------------------------------------------------------------------------------


def run() -> None:
    if not shutil.which("arm-none-eabi-gcc") or not shutil.which("arm-none-eabi-ld"):
        raise SystemExit("debug.py: arm-none-eabi binutils not found")
    variables.run()  # bundle tracks the stores
    os.makedirs(OUT, exist_ok=True)

    # DWARF TU: the variables.h externs pull in every include/*.h type; the two -f flags keep
    # GCC from dropping unused symbols/types, so the whole store lands in .debug_info.
    stub_c = OUT / "types_stub.c"
    stub_c.write_text('#include "variables.h"\n')
    _run(
        "arm-none-eabi-gcc",
        "-c",
        "-g3",
        "-O0",
        "-std=gnu11",
        "-ffreestanding",
        "-mthumb",
        "-mcpu=arm7tdmi",
        "-fno-eliminate-unused-debug-symbols",
        "-fno-eliminate-unused-debug-types",
        f"-I{INCLUDE}",
        f"-I{CARVED_INCLUDE}",
        f"-I{BUILD_INCLUDE}",
        str(stub_c),
        "-o",
        str(OUT / "types.o"),
    )

    n_funcs, n_data = _gen_syms_s(OUT / "syms.S")
    (OUT / "link.ld").write_text(LINK_LD)
    _run(
        "arm-none-eabi-gcc",
        "-c",
        "-mcpu=arm7tdmi",
        str(OUT / "syms.S"),
        "-o",
        str(OUT / "syms.o"),
    )
    _run(
        "arm-none-eabi-ld",
        "--entry=0",
        "-T",
        str(OUT / "link.ld"),
        "-o",
        str(OUT / "debug.elf"),
        str(OUT / "types.o"),
        str(OUT / "syms.o"),
    )
    # drop the GAS mapping symbols ($d over the .org zero fill); arm_pc_is_thumb prefers
    # them over the msym thumb bit, and $d would force ARM breakpoints/disassembly
    _run(
        "arm-none-eabi-objcopy",
        "--strip-symbol=$d",
        "--strip-symbol=$a",
        "--strip-symbol=$t",
        str(OUT / "debug.elf"),
    )

    tu_elfs = _build_tu_elfs()
    defined = {name for _, names in tu_elfs for name in names}
    stubs_elf, n_stubs = _build_stubs_elf(_header_prototypes(), defined)

    adds = [f"add-symbol-file {elf}" for elf, _ in tu_elfs]
    if stubs_elf:
        adds.append(f"add-symbol-file {stubs_elf}")
    adds_text = "\n".join(adds) + "\n"

    script = OUT / "rotk.gdb"
    script.write_text(
        GDB_SCRIPT.format(
            script=script,
            elf=OUT / "debug.elf",
            settings=GDB_SETTINGS,
            adds=adds_text,
            utils=OUT / "utils.gdb",
        )
    )
    hack_script = OUT / "rotk_hack.gdb"
    hack_script.write_text(
        GDB_HACK_SCRIPT.format(
            script=hack_script,
            elf=OUT / "debug.elf",
            modcode=BUILD / "hack.elf",
            settings=GDB_SETTINGS,
            adds=adds_text,
            utils=OUT / "utils.gdb",
        )
    )
    utils_script = OUT / "utils.gdb"
    utils_script.write_text(UTILS_GDB)

    print(
        f"wrote {os.path.relpath(OUT / 'debug.elf', ROOT)}: "
        f"{n_funcs} functions, {n_data} data symbols, DWARF from build/include/variables.h"
    )
    print(
        f"wrote {os.path.relpath(OUT / 'tu', ROOT)}: {len(defined)} decompiled functions "
        f"with agbcc DWARF (args, locals, lines) from {len(tu_elfs)} TUs"
    )
    if stubs_elf:
        print(
            f"wrote {os.path.relpath(stubs_elf, ROOT)}: "
            f"{n_stubs} prototype stubs (typed args at entry)"
        )
    print(f"wrote {os.path.relpath(script, ROOT)}: mgba-qt -g rotk.gba, then gdb -x it")
    print(
        f"wrote {os.path.relpath(hack_script, ROOT)}: "
        + (
            "mgba-qt -g build/rotk_hack.gba, then gdb -x it"
            if (BUILD / "hack.elf").is_file()
            else "run `make hack` first (needs build/hack.elf)"
        )
    )
    print(
        f"wrote {os.path.relpath(utils_script, ROOT)}: "
        f"`settle` utility (sourced by both scripts)"
    )
