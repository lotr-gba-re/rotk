"""Emit compile_commands.json so clangd indexes the whole decompiled tree, and regenerate
hacks/compile_flags.txt so clangd sees the HACK_<patch> selection.

compile_flags.txt alone only indexes files you open; this lists every .c under src/c and
carved/data so workspace-symbol search covers them cold. The list is on-disk .c files, not
split.cfg, so work-in-progress files show up the moment the file exists. Flags mirror
compile_flags.txt (clang parsing, not the real build).
Gitignored per-developer artifact: `make clangd`; `make verify` and `make hack` force-refresh
it too.

hacks/ is different: clangd resolves those files through hacks/compile_flags.txt (a
per-directory flags file shadows this DB in clangd's upward search, and it also covers
headers opened directly, where the #if HACK_* guards live). That file carries the
-DHACK_<patch>=0/1 selection the build derives in make/hack.mk, regenerated here from
hacks/patches.cfg; gitignored like the DB.
"""

import glob
import json
import os

from rotkit.paths import CARVED_DATA, ROOT, SRC_C

HACKS = ROOT / "hacks"

OUT = ROOT / "compile_commands.json"
HACK_FLAGS_OUT = HACKS / "compile_flags.txt"
# Mirrors cc.py: promote missing-prototypes in-editor too, so a global without a
# hand-written header prototype is flagged immediately. Only this one warning is promoted
# so unrelated clang-only diagnostics don't become spurious editor errors.
FLAGS = [
    "clang",
    "--target=arm-none-eabi",
    "-std=gnu11",
    "-ffreestanding",
    "-Iinclude",
    "-Icarved/include",
    "-Ibuild/include",
    "-Ibuild",
    # era libc headers, as compile.py's cpp step (stddef.h's size_t matches agbcc)
    "-Itools/agbcc/include",
    "-Werror=missing-prototypes",
    "-Wall",
    "-W",  # Old way of specifying -Wextra
]


# hacks/ flags, relative to hacks/ (compile_flags.txt paths resolve from its own directory).
# Mirrors MODCODE_CFLAGS in make/hack.mk minus the codegen-only options clang parsing
# doesn't need.
HACK_FLAGS = [
    "# generated by `make clangd` (rotkit build clangd); the -DHACK_* lines track hacks/patches.cfg",
    "--target=arm-none-eabi",
    "-std=gnu11",
    "-ffreestanding",
    "-fno-strict-aliasing",
    "-mlong-calls",
    "-I../include",
    "-I../carved/include",
    "-I../build/include",
    "-I../build",
    "-I../carved/data",
    "-I.",
    "-I../build/hack_include",
    "-Wall",
    "-Wextra",
]


def _hack_defines() -> list[str]:
    """The -DHACK_* selection, derived from patches.cfg as make/hack.mk derives DEF."""
    patches = sorted(p.name for p in (HACKS / "patches").iterdir() if p.is_dir())
    cfg = {
        word
        for line in (HACKS / "patches.cfg").read_text().splitlines()
        for word in line.split("#", 1)[0].split()
    }
    sel = [p for p in patches if p in cfg]
    have_tab = any((HACKS / "patches" / p / "tables.c").is_file() for p in sel)
    return [f"-DHACK_{p}={int(p in cfg)}" for p in patches] + [
        f"-DHACK_HAVE_TABLES={int(have_tab)}",
    ]


def _write(path, body: str) -> None:
    # Skip the write when nothing changed: verify force-refreshes this on every build, so a stable
    # mtime stops clangd reloading a byte-identical DB each time.
    rel = os.path.relpath(path, ROOT)
    if path.is_file() and path.read_text() == body:
        print(f"{rel} unchanged")
        return
    path.write_text(body)
    print(f"wrote {rel}")


def run() -> None:
    srcs = sorted(
        os.path.relpath(path, ROOT)
        for dir in (SRC_C, CARVED_DATA)
        for path in glob.glob(str(dir / "**" / "*.c"), recursive=True)
    )
    # directory must be a plain string: json.dump cannot serialize pathlib.Path.
    db = [
        {"directory": str(ROOT), "file": src, "arguments": FLAGS + [src]}
        for src in srcs
    ]
    _write(OUT, json.dumps(db, indent=2) + "\n")
    _write(HACK_FLAGS_OUT, "\n".join(HACK_FLAGS + _hack_defines()) + "\n")
